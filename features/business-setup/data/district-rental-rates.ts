/**
 * Verilen İl ve İlçe için geçerli m² kira çarpanını bulur.
 */
export function getDistrictRentalRate(cityName: string, districtName?: string): number {
  const cityData = TURKEY_CITY_RENTAL_RATES[cityName];
  if (!cityData) {
    return 200; // Varsayılan Anadolu baz m² kira bedeli
  }

  if (districtName && cityData.districtRates[districtName]) {
    return cityData.districtRates[districtName];
  }

  // İlçede eşleşme yoksa il varsayılanı döndür
  return cityData.defaultM2Rate || 200;
}

/**
 * İlk taşınma peşinatını hesaplar (Varsayılan: 1 Aylık Peşin + 1 Aylık Depozito = 2x Kira)
 */
export function calculateLeaseInitialCost(
  monthlyRent: number,
  depositMonths: number = 1,
  includeBrokerFee: boolean = false
): {
  firstMonthRent: number;
  deposit: number;
  brokerFee: number;
  totalLeaseUpfront: number;
} {
  const firstMonthRent = monthlyRent;
  const deposit = monthlyRent * depositMonths;
  const brokerFee = includeBrokerFee ? monthlyRent : 0;
  const totalLeaseUpfront = firstMonthRent + deposit + brokerFee;

  return {
    firstMonthRent,
    deposit,
    brokerFee,
    totalLeaseUpfront,
  };
}
